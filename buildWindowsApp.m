function paths = buildWindowsApp(runtimeDelivery)
%BUILDWINDOWSAPP Compile and package the Windows desktop application.
% buildWindowsApp('web') creates an installer that downloads MATLAB Runtime.
% buildWindowsApp('installer') embeds a previously downloaded matching Runtime.
% This function builds the app only; it does not launch or test the application.
if nargin < 1, runtimeDelivery = 'web'; end
runtimeDelivery = validatestring(runtimeDelivery, {'web','installer'});
appVersion = '1.0.1';
installerName = ['SpectralML_Toolkit_' strrep(appVersion,'.','_') '_Setup'];
assert(ispc, 'SpectralML:BuildPlatform', 'Build the Windows application on Windows.');
assert(license('test','Compiler'), 'SpectralML:BuildDependency', ...
    'Building requires MATLAB Compiler. End users do not need a MATLAB license.');
assert(license('test','Statistics_Toolbox') && license('test','Neural_Network_Toolbox'), ...
    'SpectralML:BuildDependency', ...
    'Building all models requires Statistics and Machine Learning Toolbox and Deep Learning Toolbox.');
if strcmp(runtimeDelivery,'installer')
    runtimeInstaller = mcrinstaller;
    assert(~isempty(runtimeInstaller) && isfile(runtimeInstaller), ...
        'SpectralML:RuntimeInstaller', ...
        'Download the matching Runtime with compiler.runtime.download, then rebuild.');
end

root = fileparts(mfilename('fullpath'));
folders = {'feature_selection','optimization','plotting','preprocessing', ...
    'regression','sampling','ui','utils'};
addpath(root);
additionalFiles = cellfun(@(name) fullfile(root,name), folders, 'UniformOutput',false);
for k = 1:numel(additionalFiles), addpath(additionalFiles{k}); end
additionalFiles = [additionalFiles, {fullfile(root,'predictNewSpectra.m')}];
tag = char(datetime('now','Format','yyyyMMdd_HHmmss_SSS'));
paths.build = fullfile(root,'build','windows',tag);
paths.distribution = fullfile(root,'dist','windows',tag);
paths.executable = fullfile(paths.build,'SpectralML_Toolkit.exe');
paths.installer = fullfile(paths.distribution,[installerName '.exe']);
mkdir(paths.build);
mkdir(paths.distribution);

fprintf('Building SpectralML-Toolkit %s with MATLAB %s\n',appVersion,version);
fprintf('Build directory: %s\n',paths.build);
results = compiler.build.standaloneWindowsApplication( ...
    fullfile(root,'launchSpectralML.m'), ...
    'ExecutableName','SpectralML_Toolkit', ...
    'ExecutableVersion',[appVersion '.0'], ...
    'AdditionalFiles',additionalFiles, ...
    'AutoDetectDataFiles','off', ...
    'OutputDir',paths.build, ...
    'Verbose','on');

fprintf('Creating installer (Runtime delivery: %s).\n',runtimeDelivery);
readme = fullfile(root,'packaging','QUICK_START.txt');
example = fullfile(root,'examples','example_spectra.csv');
licenseFile = fullfile(root,'LICENSE');
compiler.package.installer(results, ...
    'ApplicationName','SpectralML-Toolkit', ...
    'Version',appVersion, ...
    'InstallerName',installerName, ...
    'Summary','Spectral preprocessing and regression analysis', ...
    'Description','Import spectral data, configure a pipeline, train regression models, and export prediction diagnostics.', ...
    'InstallationNotes','This application requires MATLAB Runtime R2023a. The installer handles the required Runtime. Full MATLAB is not required.', ...
    'RuntimeDelivery',runtimeDelivery, ...
    'Shortcut',paths.executable, ...
    'AdditionalFiles',{readme,example,licenseFile}, ...
    'OutputDir',paths.distribution);
copyfile(readme,fullfile(paths.distribution,'QUICK_START.txt'));
copyfile(example,fullfile(paths.distribution,'example_spectra.csv'));
copyfile(licenseFile,fullfile(paths.distribution,'LICENSE'));
fprintf('Installer: %s\n',paths.installer);
fprintf('Build completed. Application behavior has not been tested by this build command.\n');
end
